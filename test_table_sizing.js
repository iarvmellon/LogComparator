const fs = require('fs');
const assert = require('assert');
(async () => {
  const source = fs.readFileSync('logcomparator_ui/assets/table_sizing.js', 'utf8');
  const {measureColumnWidths, fitColumnWidths, installColumnSizing} = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
  const context = {font:'', measureText(text) {
    const scale = this.font.startsWith('800') ? 1.5 : 1;
    return {width:[...text].reduce((sum,c)=>sum+(c==='W'?12:c==='i'?2:6),0)*scale};
  }};
  const columns = [{name:'id',field:'id',label:'ID',sortable:true}];
  const rows = [{id:'iiiiiiiiii'}, {id:'WWWWWWWWWWWW'}];
  assert.equal(measureColumnWidths(columns,rows,context,'400 13px Arial','800 15px Arial').id, 164);
  assert.equal(measureColumnWidths(columns,[],context,'400 13px Arial','800 15px Arial').id, 62);
  const widerHeader = [{name:'id',label:'Very long heading',sortable:true}];
  assert(measureColumnWidths(widerHeader,[],context,'400 13px Arial','800 15px Arial').id > 100);
  assert.equal(measureColumnWidths(columns,[{id:null}],context,'400 13px Arial','800 15px Arial').id,62);
  const problem = [{name:'possibleproblem',label:'Possible problem'}];
  const capped = measureColumnWidths(problem,[{possibleproblem:'W'.repeat(200)}],context,'400 13px Arial','800 15px Arial');
  assert.equal(capped.possibleproblem,97*12+3*6+20);
  const wideColumns = [{name:'uid'},{name:'problem'}];
  const fitted = fitColumnWidths(wideColumns,{uid:400,problem:900},800,44,{uid:150,problem:180});
  assert.equal(fitted.uid+fitted.problem+44,800);
  assert(fitted.uid>=150 && fitted.problem>=180);
  const narrow = fitColumnWidths(wideColumns,{uid:400,problem:900},200,44,{uid:150,problem:180});
  assert.equal(narrow.uid+narrow.problem+44,200);
  const frames = [];
  let revision = '1', mutation;
  const htmlTable = {style:{}};
  const middle = {clientWidth:1000,scrollLeft:0};
  const root = {clientWidth:1000,isConnected:true, querySelector:selector=>selector==='table'?htmlTable:middle,getAttribute:()=>revision};
  global.document = {createElement:()=>({getContext:()=>context})};
  global.getComputedStyle = ()=>({fontFamily:'Arial',getPropertyValue:()=> '13px'});
  global.requestAnimationFrame = callback => {frames.push(callback);return frames.length;};
  global.ResizeObserver = class {constructor(callback){this.callback=callback;} observe(){}};
  global.MutationObserver = class {constructor(callback){mutation=callback;} observe(){}};
  const qTable = {rows:[{id:'WWWWWWWWWWWW'}], selection:'multiple'};
  let changed;
  const component = {$refs:{qRef:qTable},$el:root,columns:columns.map(c=>({...c})),
    $nextTick:async()=>{},$watch:(getter,callback)=>{changed=callback;}};
  installColumnSizing(component);
  await frames.shift()();
  assert.equal(component.columns[0].style,'width:164px;min-width:164px;max-width:164px');
  assert.equal(htmlTable.style.width,'208px');
  revision = '2';
  qTable.rows = [];
  mutation();
  await frames.shift()();
  assert.equal(htmlTable.style.width,'106px');
  component.columns = columns.map(c=>({...c}));
  changed();
  await frames.shift()();
  assert(component.columns[0].headerStyle.includes('62px'));
  console.log('Column sizing: longest offscreen value, wider header and empty values passed');
})();
